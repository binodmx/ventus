// Generates src/environments/env.ts from .env (or from process.env, e.g. in CI).
// Run automatically before `npm start`, `npm run build` and `npm test`.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envFile = path.join(root, '.env');
const outFile = path.join(root, 'src', 'environments', 'env.ts');

const fileVars = {};
if (fs.existsSync(envFile)) {
  for (const raw of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    fileVars[key] = value;
  }
}

const required = [
  'API_KEY',
  'API_URL_SET_PARAMS',
  'API_URL_DATA',
  'API_URL_CONTRACTION',
  'API_URL_DIFFUSER',
];

const get = (key) => process.env[key] ?? fileVars[key];
const missing = required.filter((key) => !get(key));
if (missing.length) {
  console.error(`set-env: missing ${missing.join(', ')}. Copy .env.example to .env and fill it in.`);
  process.exit(1);
}

const env = {
  apiKey: get('API_KEY'),
  api: {
    setParams: get('API_URL_SET_PARAMS'),
    data: get('API_URL_DATA'),
    contraction: get('API_URL_CONTRACTION'),
    diffuser: get('API_URL_DIFFUSER'),
  },
};

fs.writeFileSync(
  outFile,
  '// Generated by scripts/set-env.js from .env. Do not edit or commit.\n' +
    `export const env = ${JSON.stringify(env, null, 2)};\n`
);
console.log('set-env: wrote src/environments/env.ts');
